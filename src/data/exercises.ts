export function getProgression(chainId: string): ProgressionChain | undefined {
  return PROGRESSIONS.find(p => p.id === chainId);
}

export function getExercise(chainId: string, order: number): Exercise | undefined {
  const chain = getProgression(chainId);
  return chain?.exercises.find(e => e.progression_order === order);
}
